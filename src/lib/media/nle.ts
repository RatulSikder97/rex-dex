import "server-only";
import { execFile } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { promisify } from "node:util";
import { MEDIA_DIR, db } from "../db";
import { mediaKind, mediaPath, probe } from "../video";

const execFileAsync = promisify(execFile);

/**
 * Hand-off to pro editors. REX renders with ffmpeg; to finish a cut in
 * Premiere Pro / DaVinci Resolve / Final Cut, it exports an FCP7 XML timeline
 * (the interchange all three import) with the scene plan as markers; for After
 * Effects it writes an ExtendScript that builds the comp (footage, scene
 * markers, editable on-screen text layers) and runs it in AE.
 */

export const EXPORT_DIR = path.join(MEDIA_DIR, "exports");

interface Scene {
  start: number;
  duration: number;
  title: string;
  narration: string;
}

/** Scene timings from the Create Studio job that rendered this file, scaled to the real duration. */
function scenesFor(mediaName: string, duration: number): Scene[] {
  const row = db().prepare("SELECT plan FROM media_jobs WHERE output = ? ORDER BY created_at DESC LIMIT 1").get(mediaName) as { plan: string } | undefined;
  if (!row) return [];
  let plan: { scenes?: { durationSec?: number; onScreenText?: string; narration?: string }[] };
  try {
    plan = JSON.parse(row.plan);
  } catch {
    return [];
  }
  const raw = plan.scenes ?? [];
  const total = raw.reduce((a, s) => a + (s.durationSec ?? 0), 0);
  if (!raw.length || !total) return [];
  const k = duration / total;
  let t = 0;
  return raw.map((s, i) => {
    const d = (s.durationSec ?? 0) * k;
    const scene = { start: t, duration: d, title: s.onScreenText?.trim() || `Scene ${i + 1}`, narration: s.narration ?? "" };
    t += d;
    return scene;
  });
}

const xml = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const fileUrl = (p: string) => "file://" + p.split("/").map(encodeURIComponent).join("/");

/** FCP7 XML (xmeml v4): imports in Premiere Pro (File ▸ Import), DaVinci Resolve and Final Cut (via XtoCC). */
export async function exportFcpXml(mediaName: string): Promise<string> {
  const src = mediaPath(mediaName);
  const info = await probe(mediaName);
  const fps = Math.round(info.fps || 30);
  const frames = Math.max(1, Math.round(info.duration * fps));
  const w = info.width ?? 1920;
  const h = info.height ?? 1080;
  const base = mediaName.replace(/\.[^.]+$/, "");
  const scenes = scenesFor(mediaName, info.duration);
  const rate = `<rate><timebase>${fps}</timebase><ntsc>FALSE</ntsc></rate>`;
  const markers = scenes
    .map((s) => `<marker><name>${xml(s.title)}</name><comment>${xml(s.narration)}</comment><in>${Math.round(s.start * fps)}</in><out>-1</out></marker>`)
    .join("");
  const file = `<file id="file-1"><name>${xml(mediaName)}</name><pathurl>${xml(fileUrl(src))}</pathurl>${rate}<duration>${frames}</duration><media><video><samplecharacteristics><width>${w}</width><height>${h}</height></samplecharacteristics></video>${info.hasAudio ? "<audio><channelcount>2</channelcount></audio>" : ""}</media></file>`;
  const clip = (kind: "video" | "audio", first: boolean) =>
    `<clipitem id="${kind}-1"><name>${xml(mediaName)}</name><duration>${frames}</duration>${rate}<start>0</start><end>${frames}</end><in>0</in><out>${frames}</out>${first ? file : '<file id="file-1"/>'}${kind === "audio" ? "<sourcetrack><mediatype>audio</mediatype><trackindex>1</trackindex></sourcetrack>" : ""}</clipitem>`;
  const doc = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE xmeml>
<xmeml version="4">
<sequence id="sequence-1"><name>${xml(base)} (REX)</name><duration>${frames}</duration>${rate}
<media>
<video><format><samplecharacteristics>${rate}<width>${w}</width><height>${h}</height></samplecharacteristics></format><track>${clip("video", true)}</track></video>
${info.hasAudio ? `<audio><track>${clip("audio", false)}</track></audio>` : ""}
</media>
${markers}
</sequence>
</xmeml>
`;
  fs.mkdirSync(EXPORT_DIR, { recursive: true });
  const out = path.join(EXPORT_DIR, `${base}.xml`);
  fs.writeFileSync(out, doc);
  return out;
}

/** After Effects ExtendScript: comp from the footage + scene markers + editable text layers. */
export async function exportAeScript(mediaName: string): Promise<string> {
  const src = mediaPath(mediaName);
  const info = await probe(mediaName);
  const fps = info.fps || 30;
  const w = info.width ?? 1920;
  const h = info.height ?? 1080;
  const base = mediaName.replace(/\.[^.]+$/, "");
  const scenes = scenesFor(mediaName, info.duration);
  const js = JSON.stringify;
  const script = `// Generated by REX: builds an editable After Effects comp for ${mediaName}
app.beginUndoGroup("REX: ${base.replace(/"/g, "")}");
var footage = app.project.importFile(new ImportOptions(new File(${js(src)})));
var comp = app.project.items.addComp(${js(base + " (REX)")}, ${w}, ${h}, 1, ${Math.max(info.duration, 1 / fps)}, ${fps});
comp.layers.add(footage);
var scenes = ${js(scenes)};
for (var i = 0; i < scenes.length; i++) {
  var s = scenes[i];
  var mv = new MarkerValue(s.title);
  mv.comment = s.narration;
  comp.markerProperty.setValueAtTime(s.start, mv);
  var t = comp.layers.addText(s.title);
  t.name = "Scene " + (i + 1) + " title";
  t.inPoint = s.start;
  t.outPoint = s.start + s.duration;
  var doc = t.property("Source Text").value;
  doc.fontSize = ${Math.round(h / 16)};
  doc.fillColor = [1, 1, 1];
  doc.justification = ParagraphJustification.CENTER_JUSTIFY;
  t.property("Source Text").setValue(doc);
  t.property("Position").setValue([${w / 2}, ${Math.round(h * 0.18)}]);
  t.enabled = false; // REX already burned titles in; enable to restyle them here.
}
comp.openInViewer();
app.endUndoGroup();
`;
  fs.mkdirSync(EXPORT_DIR, { recursive: true });
  const out = path.join(EXPORT_DIR, `${base}.jsx`);
  fs.writeFileSync(out, script);
  return out;
}

/** Opens a file with a macOS app bundle (`open -a`). */
export async function openWithApp(appPath: string, file: string) {
  await execFileAsync("open", ["-a", appPath, file], { timeout: 15_000 });
}

/** Runs an ExtendScript in After Effects through AppleScript (AE must allow scripting). */
export async function runInAfterEffects(appPath: string, scriptFile: string) {
  const appName = path.basename(appPath, ".app");
  await execFileAsync("osascript", ["-e", `tell application ${JSON.stringify(appName)} to activate`, "-e", `tell application ${JSON.stringify(appName)} to DoScriptFile ${JSON.stringify(scriptFile)}`], { timeout: 60_000 });
}

export function assertVideo(name: string) {
  if (mediaKind(name) !== "video") throw new Error("Pick a video file");
}
